// client/src/utils/specialityName.js
//
// Подпись врачебной специальности на языке интерфейса.
//
// Английское имя («Otolaryngologist») — это КЛЮЧ: оно хранится в профиле
// врача, по нему идут фильтры и сравнение. Переводим только показ, само
// значение не трогаем — иначе развалятся фильтр по специальности и связь
// профиля со справочником.
//
// Где переводим и где нет. Врачу английское имя привычнее и точнее:
// номенклатура международная. А пациент по нему ищет врача — и «Otolaryngologist»
// на арабской странице клиники он просто не опознает. Поэтому подпись
// подставляется на страницах, которые видит пациент (поиск врача, витрина,
// профиль), а в кабинете врача остаётся как есть.
//
// Если названия нет в словаре — показываем исходное имя. Новая специальность
// появляется в базе раньше, чем перевод, и пустое место было бы хуже латиницы.

import i18n from "../i18n";

const NS = "specializations";

/**
 * @param {unknown} name имя специальности, как оно пришло с сервера
 * @param {(key: string, opts?: object) => string} [t] переводчик; без него
 *   берётся глобальный экземпляр i18n — удобно вне компонентов (SEO, утилиты)
 * @returns {string} подпись на языке интерфейса или исходное имя
 */
export function specialityName(name, t) {
  if (typeof name !== "string" || !name.trim()) return "";
  const key = name.trim();

  // Словарь грузится по требованию: 106 названий нужны не на каждой
  // странице, а только там, где выбирают врача.
  if (!i18n.hasResourceBundle(i18n.language, NS)) {
    i18n.loadNamespaces(NS).catch(() => {});
  }

  const translate = t || i18n.t.bind(i18n);
  const value = translate(`${NS}:${key}`, { defaultValue: "" });
  return value && value !== key ? value : key;
}

export default specialityName;
