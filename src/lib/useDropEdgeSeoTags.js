// lib/useDropEdgeSeoTags.js
//
// Снять SEO-теги, впрыснутые edge-функцией, после того как страница
// поставила свои через Helmet.
//
// Зачем. Мета-теги на публичных страницах пишут ДВА слоя, и оба нужны:
//
//   1. netlify/edge-functions/seo.js — правит сырой HTML на пограничном
//      узле. Только его и видят роботы, не выполняющие JS, а также
//      разворачиватели ссылок в мессенджерах (WhatsApp, Telegram);
//   2. Helmet в самом компоненте — работает после гидратации и умеет то,
//      чего edge не умеет: обновляться при смене языка прямо на странице.
//
// Helmet не знает о чужих тегах и свои просто добавляет. В результате на
// странице новости оказывалось два canonical, два og:url, ДВЕНАДЦАТЬ
// hreflang вместо шести и три блока JSON-LD. Одинаковые значения Google
// переживает, но стоит слоям разойтись — и это уже противоречивые
// указания на одной странице.
//
// Поэтому edge помечает всё, что впрыснул, атрибутом data-seo="edge", а
// страница, у которой есть собственный Helmet, снимает эти теги при
// монтировании. Роботам без JS достаётся версия edge, всем остальным —
// версия Helmet, и ровно одна.
//
// ВАЖНО: вызывать только там, где Helmet действительно ставит замену.
// На странице без Helmet этот хук просто отнял бы у неё всю разметку.

import { useEffect } from "react";

export function useDropEdgeSeoTags(ready = true) {
  useEffect(() => {
    // ready === false означает «Helmet ещё нечего было ставить»: пока
    // материал не загружен, снимать теги edge рано — на этот момент они
    // единственные, что есть на странице.
    if (!ready) return;

    // Отложено до следующего кадра: Helmet пишет в <head> в собственном
    // эффекте, и порядок между двумя эффектами не гарантирован. Снять
    // раньше, чем он поставил, — значит на мгновение остаться без
    // мета-тегов вовсе.
    const id = requestAnimationFrame(() => {
      document
        .querySelectorAll('head [data-seo="edge"]')
        .forEach((el) => el.remove());
    });

    return () => cancelAnimationFrame(id);
  }, [ready]);
}

export default useDropEdgeSeoTags;
