// client/src/lib/sanitizeHtml.js
//
// Единая точка санитизации HTML перед dangerouslySetInnerHTML.
//
// ЗАЧЕМ: контент статей, био врачей, медицинских шаблонов и т.п. — это HTML,
// созданный пользователями (через CKEditor/Quill). Рендер его напрямую через
// dangerouslySetInnerHTML без очистки = stored XSS: автор (или тот, кто угнал
// его аккаунт) вставляет <script>/onerror — код выполняется у КАЖДОГО читателя,
// включая пациентов. DOMPurify вырезает скрипты/обработчики событий, оставляя
// безопасную разметку.
//
// Использование:
//   import { sh } from "../../../lib/sanitizeHtml";
//   <div dangerouslySetInnerHTML={{ __html: sh(article.content) }} />

import DOMPurify from "dompurify";

/**
 * Очистить строку HTML от исполняемого кода. null/undefined → "".
 * @param {string} dirty
 * @returns {string}
 */
export function sh(dirty) {
  if (dirty == null) return "";
  return DOMPurify.sanitize(String(dirty), {
    // target=_blank ссылки безопасны, но DOMPurify по умолчанию их не трогает.
    // Явно запрещаем javascript: и data: в href/src через дефолтную политику.
    USE_PROFILES: { html: true },
  });
}

export default sh;

/**
 * Текст, который МОГ быть написан и до появления редактора.
 *
 * Биография врача годами хранилась обычным текстом с переводами строк, а
 * теперь её пишут в CKEditor и она приходит разметкой. В базе лежит и то,
 * и другое, и переписывать старое незачем: одна проверка решает оба
 * случая.
 *
 * Признак разметки — «<» перед буквой: у обычного текста так не бывает,
 * а «7 < 9» не обманет. Если разметки нет, переводы строк превращаются в
 * <br>, иначе абзацы старых биографий склеились бы в одну простыню.
 *
 * Экранировать вручную не нужно: DOMPurify ниже всё равно вырежет всё
 * опасное, а «<» без буквы браузер покажет как есть.
 */
export function shRich(value) {
  const текст = value == null ? "" : String(value);
  if (!текст) return "";
  const разметка = /<[a-z][\s\S]*>/i.test(текст);
  return sh(разметка ? текст : текст.replace(/\r?\n/g, "<br>"));
}

/**
 * Обычный текст → разметка, годная для редактора.
 *
 * ЗАЧЕМ. CKEditor принимает HTML. Биографии, написанные до его появления,
 * лежат в базе обычным текстом с переводами строк — а в HTML перевод
 * строки это просто пробел. Врач открывал редактирование профиля и видел,
 * как его аккуратно разбитая на разделы биография превращается в сплошную
 * стену слов: структура не «терялась при копировании», её съедал сам
 * редактор при загрузке.
 *
 * Пустая строка разделяет абзацы, одиночный перевод строки — это <br>
 * внутри абзаца. Так ведут себя все текстовые редакторы, и так текст
 * выглядел до того, как его туда положили.
 *
 * Разметку не трогаем: она уже разметка.
 */
export function текстВРазметку(value) {
  const текст = value == null ? "" : String(value);
  if (!текст.trim()) return "";
  if (/<[a-z][\s\S]*>/i.test(текст)) return текст;

  // Экранируем ДО вставки тегов: иначе «<» из текста станет тегом, а
  // вставленные нами <p> и <br> экранируются заодно с ним.
  const экранировать = (t) =>
    t
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");

  return текст
    .replace(/\r\n/g, "\n")
    .split(/\n[ \t]*\n+/)
    .map((абзац) => абзац.trim())
    .filter(Boolean)
    .map((абзац) => `<p>${экранировать(абзац).replace(/\n/g, "<br>")}</p>`)
    .join("");
}
