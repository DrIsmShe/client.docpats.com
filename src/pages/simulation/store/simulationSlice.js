/* ──────────────────────────────────────────────────────────────────────────
   S.7.7+ — URL normalization для photo.url:
     Backend возвращает proxy URL как относительный путь
     (/api/simulation/photos/proxy?key=...). Все потребители — Redux state,
     CSS background-image, <img src>, fetch — ожидают абсолютный URL.
     Нормализуем ОДИН РАЗ при получении плана из backend, чтобы компоненты
     работали без лишней логики.
   ────────────────────────────────────────────────────────────────────────── */

function normalizePhotoUrl(url) {
  if (!url) return url;
  // Полный URL — без изменений
  if (url.startsWith("http://") || url.startsWith("https://")) return url;
  // Относительный → абсолютный с API_BASE
  if (url.startsWith("/")) {
    const base = (API_BASE || "").replace(/\/$/, "");
    return `${base}${url}`;
  }
  return url;
}

/**
 * Применяет normalizePhotoUrl ко всем фото-URL в плане.
 */
function normalizePlanPhotoUrls(plan) {
  if (!plan?.photo?.url) return plan;
  return {
    ...plan,
    photo: { ...plan.photo, url: normalizePhotoUrl(plan.photo.url) },
  };
}

