const DEFAULT_VISIBLE_MEASUREMENTS = {
  nasofrontalAngle: true,
  goodeProjection: true,
  alarBaseWidth: true,
};

const initialState = {
  list: [],
  listCursor: null,
  listHasMore: false,
  current: null,
  loading: {
    list: false,
    current: false,
    create: false,
    update: false,
    delete: false,
    upload: false,
    persistLandmarks: false,
  },
  error: null,
  uploadProgress: 0,
  visibleLandmarkGroups: DEFAULT_VISIBLE_GROUPS,
  visibleMeasurements: DEFAULT_VISIBLE_MEASUREMENTS,
  faceVariants: [],
  selectedFaceIndex: 0,
};

function normalizePlan(plan) {
  if (!plan) return plan;
  // S.7.7+ — Сначала фото URL, потом остальная нормализация
  const planWithPhotoUrl = normalizePlanPhotoUrls(plan);

  const rawLandmarks = Array.isArray(planWithPhotoUrl.landmarks)
    ? planWithPhotoUrl.landmarks
    : [];
  const landmarks = rawLandmarks.map((lm) => ({
    ...lm,
    hidden: Boolean(lm.hidden),
    autoGenerated: lm.autoGenerated !== false,
  }));
  const meta = planWithPhotoUrl.landmarksMeta || {};
  return {
    ...planWithPhotoUrl,
    landmarks,
    landmarksDetectedAt: meta.detectedAt || null,
    landmarksStatus: landmarks.length > 0 ? "detected" : "idle",
    landmarksSource: meta.source || "auto",
  };
}

let manualLandmarkCounter = 0;
function genManualLandmarkId() {
  manualLandmarkCounter += 1;
  return `manual_${Date.now().toString(36)}_${manualLandmarkCounter}`;
}

/* ─────── Thunks ─────── */

export const fetchPlans = createAsyncThunk(
  "simulation/fetchPlans",
  async ({ reset = true } = {}, { getState, rejectWithValue }) => {
    try {
      const state = getState().simulation;
      const cursor = reset ? null : state.listCursor;
      const result = await api.listPlans({ limit: 30, cursor });
      return { ...result, reset };
    } catch (err) {
      return rejectWithValue(err);
    }
  },
);

export const fetchPlanById = createAsyncThunk(
  "simulation/fetchPlanById",
  async (id, { rejectWithValue }) => {
    try {
      return await api.getPlan(id);
    } catch (err) {
      return rejectWithValue(err);
    }
  },
);

