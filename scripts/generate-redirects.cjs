// scripts/generate-redirects.cjs
//
// Правила «какой адрес отдаёт приложение, а какой — 404» пишутся в
// _redirects, а не в edge-функцию.
//
// ЗАЧЕМ. Раньше отсечкой занималась edge-функция: в её config.path стоял
// шаблон "/*", и она вызывалась НА КАЖДЫЙ адрес — включая все экраны
// кабинета, где ей делать нечего (она доходила до конца веток и молча
// пропускала запрос дальше). Каждый такой вызов — платная единица у
// Netlify, и счётчик выбило: сайт целиком начал отвечать 503
// usage_exceeded.
//
// Тот же результат достигается правилами CDN, которые бесплатны:
// известная зона отдаёт оболочку с 200, всё прочее — оболочку со
// статусом 404 (React покажет свой экран «страница не найдена», а робот
// получит честный статус). Edge-функция остаётся только там, где она
// действительно нужна: материалы, витрины, разделы — то есть где надо
// подставить title, canonical и разметку.
//
// ПОЧЕМУ ГЕНЕРАЦИЯ. Список зон уже есть — netlify/edge-functions/lib/
// public-routes.js, и он сверяется с App.jsx на каждой сборке. Вести
// второй такой же список руками в _redirects значит завести источник
// расхождения: забытая зона превратится в 404 на живом разделе.

const fs = require("fs");
const path = require("path");

const КОРЕНЬ = path.join(__dirname, "..");
const СПИСОК = path.join(
  КОРЕНЬ, "netlify", "edge-functions", "lib", "public-routes.js",
);
const ФАЙЛ = path.join(КОРЕНЬ, "public", "_redirects");

const НАЧАЛО = "# >>> ЗОНЫ ПРИЛОЖЕНИЯ — СГЕНЕРИРОВАНО, НЕ ПРАВИТЬ РУКАМИ >>>";
const КОНЕЦ = "# <<< ЗОНЫ ПРИЛОЖЕНИЯ <<<";

function зоны() {
  const код = fs.readFileSync(СПИСОК, "utf8");
  const блок = код.slice(
    код.indexOf("ROOT_SEGMENTS = new Set(["),
    код.indexOf("]);"),
  );
  return [...блок.matchAll(/"([^"]+)"/g)].map((m) => m[1]).sort();
}

/* dp-videra и embed уходят на другие серверы правилами выше по файлу —
   строка про оболочку для них была бы мёртвой, а в глазах читателя
   противоречила бы прокси. */
const НЕ_НАШИ = new Set(["dp-videra", "embed"]);

function собрать() {
  const строки = [
    НАЧАЛО,
    "# Источник — netlify/edge-functions/lib/public-routes.js.",
    "# Обновляется скриптом scripts/generate-redirects.cjs при сборке.",
    "",
    "/ ".padEnd(23) + "/index.html   200",
  ];

  for (const зона of зоны()) {
    if (НЕ_НАШИ.has(зона)) continue;
    строки.push(`/${зона} `.padEnd(23) + "/index.html   200");
    строки.push(`/${зона}/* `.padEnd(23) + "/index.html   200");
  }

  строки.push(
    "",
    "# Адрес приложению незнаком. Оболочка та же — React покажет свой экран",
    "# «страница не найдена», — но статус честный: иначе любая опечатка в",
    "# ссылке становится для поисковика полноценной страницей.",
    "#",
    "# Односегментные адреса (/<слаг-клиники>) сюда доходят только если",
    "# edge-функция не нашла такой витрины: она объявляет \"/:slug\" и",
    "# отрабатывает раньше правил этого файла.",
    "/* ".padEnd(23) + "/index.html   404",
    КОНЕЦ,
  );

  return строки.join("\n");
}

const текущий = fs.readFileSync(ФАЙЛ, "utf8");
const блок = собрать();

let новый;
if (текущий.includes(НАЧАЛО)) {
  новый =
    текущий.slice(0, текущий.indexOf(НАЧАЛО)) +
    блок +
    текущий.slice(текущий.indexOf(КОНЕЦ) + КОНЕЦ.length);
} else {
  // Первый запуск: старый catch-all заменяем сгенерированным блоком.
  const старый = "/* /index.html 200";
  if (!текущий.includes(старый)) {
    console.error(
      "\n_redirects: не найден ни блок зон, ни прежний catch-all " +
        `«${старый}» — правило отдачи приложения не тронуто.\n`,
    );
    process.exit(1);
  }
  новый = текущий.replace(старый, блок);
}

if (новый !== текущий) {
  fs.writeFileSync(ФАЙЛ, новый);
  console.log("_redirects: блок зон обновлён.");
} else {
  console.log("_redirects: блок зон уже актуален.");
}
