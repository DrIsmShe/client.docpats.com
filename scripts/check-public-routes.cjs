// scripts/check-public-routes.cjs
//
// Список зон приложения на edge не должен отставать от App.jsx.
//
// ЗАЧЕМ ЭТА ПРОВЕРКА. Edge-функция отвечает 404 на адрес, первый сегмент
// которого ей незнаком. Это закрывает «мягкий 404» — но ценой того, что
// забытая в списке зона превращается в 404 на живой странице. Ошибка
// несимметрична: лишний 200 на несуществующем адресе стоит места в
// отчёте Search Console, лишний 404 на рабочем разделе стоит посетителей.
//
// Поэтому список сверяется на каждой сборке. Новая зона, не попавшая в
// public-routes.js, роняет сборку — то есть обнаруживается за минуту и у
// того, кто её добавил, а не через неделю в жалобе «страница пропала».
//
// ПОЧЕМУ РАЗБОР РЕГУЛЯРКАМИ, А НЕ ПАРСЕРОМ. Нужен ровно первый сегмент
// каждого маршрута верхнего уровня; полное дерево JSX для этого разбирать
// незачем, а зависимость от парсера пришлось бы обновлять вместе с
// синтаксисом React Router.

const fs = require("fs");
const path = require("path");

const КОРЕНЬ = path.join(__dirname, "..");
const APP = path.join(КОРЕНЬ, "src", "App.jsx");
const СПИСОК = path.join(КОРЕНЬ, "netlify", "edge-functions", "public-routes.js");

/** Первые сегменты всех маршрутов App.jsx, объявленных от корня. */
function корниИзПриложения() {
  const код = fs.readFileSync(APP, "utf8");
  const строки = код.split("\n");

  const стек = []; // [отступ, полный путь]
  const корни = new Set();

  for (const строка of строки) {
    const m = строка.match(/^(\s*)<Route\s+path="([^"]+)"/);
    if (!m) continue;

    const отступ = m[1].length;
    const путь = m[2];

    while (стек.length && стек[стек.length - 1][0] >= отступ) стек.pop();
    const родитель = стек.length ? стек[стек.length - 1][1] : "";
    const полный = путь.startsWith("/")
      ? путь
      : `${родитель.replace(/\/$/, "")}/${путь}`;

    const первый = полный.replace(/^\/+/, "").split("/")[0];
    if (первый && !первый.startsWith(":") && первый !== "*") корни.add(первый);

    if (!строка.trimEnd().endsWith("/>")) стек.push([отступ, полный]);
  }

  return корни;
}

/** Сегменты, перечисленные в списке edge-функции. */
function корниИзСписка() {
  const код = fs.readFileSync(СПИСОК, "utf8");
  const блок = код.slice(
    код.indexOf("ROOT_SEGMENTS = new Set(["),
    код.indexOf("]);"),
  );
  return new Set([...блок.matchAll(/"([^"]+)"/g)].map((m) => m[1]));
}

const вПриложении = корниИзПриложения();
const вСписке = корниИзСписка();

const пропущены = [...вПриложении].filter((к) => !вСписке.has(к)).sort();

if (пропущены.length) {
  console.error(
    `\nЗОНЫ ПРИЛОЖЕНИЯ, КОТОРЫХ НЕТ В СПИСКЕ edge (${пропущены.length}):\n`,
  );
  for (const к of пропущены) console.error(`  /${к}`);
  console.error(
    "\nДобавьте их в netlify/edge-functions/public-routes.js — иначе\n" +
      "edge-функция ответит на них 404, и раздел исчезнет для посетителей.\n",
  );
  process.exit(1);
}

// Лишние в списке — не ошибка: там есть адреса, которых в App.jsx нет
// вовсе (прокси на студию и встраиваемый плеер живут в _redirects).
console.log(
  `Зоны приложения: ${вПриложении.size} из App.jsx, ${вСписке.size} в списке edge — пропусков нет.`,
);
